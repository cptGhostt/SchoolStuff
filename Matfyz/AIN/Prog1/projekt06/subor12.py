import turtle
t = turtle.Turtle()
def dom():
	t.fd(10+2*repc)
	t.lt(90)
	t.fd(10+2*repc)
	t.lt(90)
	t.fd(10+2*repc)
	t.rt(120)
	t.fd(10+2*repc)
	t.rt(120)
	t.fd(10+2*repc)
	t.rt(120)
	t.fd(10+2*repc)
	t.lt(90)
	t.fd(10+2*repc)
	t.lt(90)
	t.fd(10+2*repc)
t.pu()
t.rt(180)
t.fd(300)
t.rt(180)
t.pd()
for repc in range(1, 21):
	dom()
	t.pu()
	t.fd(5)
	t.pd()
turtle.done()
